/// 根据卦名生成爻位名称（初九/六二…上六）
String yaoPositionName(int index, bool isYang) {
  const positions = ['初', '二', '三', '四', '五', '上'];
  return '${positions[index]}${isYang ? '九' : '六'}';
}

